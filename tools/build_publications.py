"""Builds data/publications.json (the "All publications" list on research.html) from the master workbook.

Only rows ticked "On Website" are published, as for the rest of the site. Run it after editing the workbook
(or after downloading your Google Sheet as .xlsx over tools/Salvi_Master_Resume_Data.xlsx):
    python -m pip install openpyxl
    python tools/build_publications.py
"""
import json
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
WORKBOOK = ROOT / "tools" / "Salvi_Master_Resume_Data.xlsx"
OUT = ROOT / "data" / "publications.json"
HEADER_ROW = 2          # row 1 holds the column groups, row 2 the column names

# topic tick-box columns -> the tag shown on the site
TOPICS = {"Li-Fi": "Li-Fi / VLC", "VLC": "Li-Fi / VLC", "IoT": "IoT", "AI/ML": "AI / ML", "Computer Vision": "Computer Vision",
          "Healthcare": "Healthcare", "Full-Stack": "Full-Stack", "Blockchain": "Blockchain", "AR/VR": "AR / VR", "Robotics": "Robotics"}

# sheet -> publication type, and which column holds each field
SHEETS = {
    "Publications-Journals": ("Journal", {"venue": "Journal", "details": "Vol/Issue/Pages", "indexed": "Indexed (SCI/Scopus)",
                                          "link": "DOI / Link", "role": "Role (First/Co)", "with": "Co-authors"}),
    "Publications-Conferences": ("Conference", {"venue": "Conference", "details": "Vol/Pages", "indexed": "Indexed (SCI/Scopus/WoS)",
                                                "link": "DOI / Link", "role": "Role", "with": "Co-authors"}),
    "Books-Chapters": ("Book chapter", {"venue": "Publisher", "details": "ISBN/ISSN", "authors": "Author(s)"}),
}


def text(v):
    return "" if v is None else str(v).strip()


def rows(ws):
    data = list(ws.iter_rows(values_only=True))
    names = [text(h) for h in data[HEADER_ROW - 1]]
    for r in data[HEADER_ROW:]:
        rec = {names[i]: r[i] for i in range(min(len(names), len(r))) if names[i]}
        if text(rec.get(names[0])):
            yield names[0], rec


def main():
    wb = openpyxl.load_workbook(WORKBOOK, read_only=True, data_only=True)
    items = []
    for sheet, (kind, cols) in SHEETS.items():
        for title_col, rec in rows(wb[sheet]):
            if rec.get("On Website") is not True:
                continue
            link = text(rec.get(cols.get("link", ""), ""))
            item = {
                "type": kind,
                "title": text(rec[title_col]),
                "venue": text(rec.get(cols["venue"])),
                "year": text(rec.get("Year")),
                "details": text(rec.get(cols["details"])),
                "indexed": text(rec.get(cols.get("indexed", ""), "")),
                "link": link if link.startswith("http") else "",
                "role": text(rec.get(cols.get("role", ""), "")),
                "with": text(rec.get(cols.get("with", ""), "")),
                "authors": text(rec.get(cols.get("authors", ""), "")),
                "topics": sorted({tag for col, tag in TOPICS.items() if rec.get(col) is True}),
            }
            items.append({k: v for k, v in item.items() if v not in ("", [])} | {"topics": item["topics"]})
    items.sort(key=lambda x: (-int(x["year"]) if x.get("year", "").isdigit() else 0, x["type"], x["title"]))
    counts = {k: sum(1 for x in items if x["type"] == k) for k, _ in SHEETS.values()}
    OUT.write_text(json.dumps({"_help": "GENERATED by tools/build_publications.py from the master workbook (rows ticked On Website). Do not edit by hand.",
                               "counts": counts, "items": items}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(items)} publications {counts}")


if __name__ == "__main__":
    main()
